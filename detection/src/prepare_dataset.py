#!/usr/bin/env python3
"""Build a clean, derived YOLO dataset from the BnF delivery.

The delivery (`datasets/20250214-segmentation-dataset-iiif/`) is treated as read-only:
nothing is written into it. The derived dataset is produced in `detection/data/`, with
symlinks to the images to avoid duplicating 1.1 GB.

Cleanups applied:
  - class filtering (default: Illustration only, i.e. `nc=1`)
  - removal of exact duplicate boxes (46 found in the delivery)
  - removal of zero-area boxes (1 found)
  - empty label files are kept: they are pure negatives

Usage:
    uv run python detection/src/prepare_dataset.py                # nc=1, illustrations only
    uv run python detection/src/prepare_dataset.py --classes 0 1  # nc=2, for the ablation
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

from config import DATA, DELIVERY

SOURCE = DELIVERY
SOURCE_NAMES = {0: "Illustration", 1: "Texte"}
SPLITS = ("train", "val")


def read_boxes(path: Path) -> list[tuple[int, float, float, float, float]]:
    """Parse a YOLO label file. Malformed lines are reported, not ignored."""
    boxes = []
    for num, line in enumerate(path.read_text().splitlines(), 1):
        if not line.strip():
            continue
        fields = line.split()
        if len(fields) != 5:
            raise ValueError(f"{path.name} line {num}: {len(fields)} fields instead of 5")
        cls, *coords = fields
        boxes.append((int(cls), *map(float, coords)))
    return boxes


def clean(boxes, kept_classes):
    """Filter classes, deduplicate, drop degenerate boxes.

    Returns (clean_boxes, counters) so the cleanup can be reported.
    """
    kept, seen = [], set()
    n_filtered = n_duplicates = n_degenerate = 0

    for cls, cx, cy, w, h in boxes:
        if cls not in kept_classes:
            n_filtered += 1
            continue
        if w <= 0 or h <= 0:
            n_degenerate += 1
            continue
        key = (cls, round(cx, 6), round(cy, 6), round(w, 6), round(h, 6))
        if key in seen:
            n_duplicates += 1
            continue
        seen.add(key)
        # reindexing: kept classes become 0..n-1, in their original order
        kept.append((kept_classes.index(cls), cx, cy, w, h))

    return kept, (n_filtered, n_duplicates, n_degenerate)


def prepare(out: Path, classes: list[int], force: bool) -> None:
    if out.exists():
        if not force:
            raise SystemExit(f"{out} already exists — rerun with --force to overwrite it.")
        shutil.rmtree(out)

    names = [SOURCE_NAMES[c] for c in classes]
    print(f"Kept classes: {names}  (nc={len(classes)})")
    print(f"Source: {SOURCE}")
    print(f"Output: {out}\n")

    total = {"boxes": 0, "filtered": 0, "duplicates": 0, "degenerate": 0}

    for split in SPLITS:
        dst_img = out / split / "images"
        dst_lbl = out / split / "labels"
        dst_img.mkdir(parents=True)
        dst_lbl.mkdir(parents=True)

        src_img = SOURCE / split / "images"
        src_lbl = SOURCE / split / "labels"

        n_views = n_empty = n_boxes = 0
        for file in sorted(src_lbl.glob("*.txt")):
            cleaned, (f_, d_, g_) = clean(read_boxes(file), classes)
            total["filtered"] += f_
            total["duplicates"] += d_
            total["degenerate"] += g_

            # an empty file stays a file: it is a pure negative, not a missing label
            (dst_lbl / file.name).write_text(
                "".join(f"{c} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}\n" for c, cx, cy, w, h in cleaned)
            )

            image = src_img / f"{file.stem}.jpg"
            if not image.exists():
                raise SystemExit(f"missing image for {file.name}")
            (dst_img / image.name).symlink_to(image.resolve())

            n_views += 1
            n_boxes += len(cleaned)
            n_empty += not cleaned

        total["boxes"] += n_boxes
        print(f"  {split:<6} {n_views:>5} views · {n_boxes:>6} boxes · {n_empty:>4} views without boxes (negatives)")

    yaml = out / "dataset.yaml"
    yaml.write_text(
        "# Generated by prepare_dataset.py — absolute paths, local machine\n"
        f"path: {out.resolve()}\n"
        "train: train/images\n"
        "val: val/images\n"
        f"nc: {len(classes)}\n"
        "names:\n" + "".join(f"  {i}: {n}\n" for i, n in enumerate(names))
    )

    print(f"\nCleanup: {total['filtered']} boxes filtered (dropped class) · "
          f"{total['duplicates']} duplicates · {total['degenerate']} degenerate")
    print(f"Total kept: {total['boxes']} boxes")
    print(f"\nConfig written: {yaml}")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--classes", type=int, nargs="+", default=[0],
                   help="source classes to keep (0=Illustration, 1=Texte). Default: 0")
    p.add_argument("--out", type=Path, default=None,
                   help="output folder. Default: detection/data/detection-nc<N>")
    p.add_argument("--force", action="store_true", help="overwrite the output folder if it exists")
    args = p.parse_args()

    unknown = set(args.classes) - set(SOURCE_NAMES)
    if unknown:
        raise SystemExit(f"unknown classes: {sorted(unknown)}")

    out = args.out or DATA / f"detection-nc{len(args.classes)}"
    prepare(out, args.classes, args.force)


if __name__ == "__main__":
    main()
